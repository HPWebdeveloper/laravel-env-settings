<?php

declare(strict_types=1);

namespace HpWebDeveloper\LaravelEnvSettings;

use BackedEnum;
use HpWebDeveloper\LaravelEnvSettings\Contracts\EnvironmentAware;
use InvalidArgumentException;
use ReflectionClass;
use ReflectionProperty;
use UnitEnum;

abstract class EnvironmentSettings implements EnvironmentAware
{
    abstract public static function development(): static;

    abstract public static function production(): static;

    public static function staging(): static
    {
        return static::development();
    }

    public static function testing(): static
    {
        return static::development();
    }

    /**
     * Resolve the correct instance for the current environment.
     *
     * Delegates to the container-bound {@see EnvSettingsResolver} so the
     * resolution strategy is injectable and testable without the class
     * knowing how to build itself.
     */
    public static function resolve(): static
    {
        /** @var static */
        return app(EnvSettingsResolver::class)->resolve(static::class);
    }

    /**
     * Resolve this settings class as if `APP_ENV` were the given environment.
     *
     * The application's environment is swapped so the real resolution path runs
     * — `#[Environment]` attributes, `environment_map` and local overrides all
     * included — then restored, whatever happens.
     */
    public static function from(string $environment): static
    {
        $original = app()->environment();

        app()->detectEnvironment(fn (): string => $environment);

        try {
            return static::resolve();
        } finally {
            app()->detectEnvironment(fn (): string => $original);
        }
    }

    /**
     * Bind a partial double of this settings class into the container.
     *
     * Restating every constructor argument to change one value makes tests
     * break whenever a property is added, so start from a real environment and
     * replace only what the test cares about:
     *
     *     AuthSettings::fake(['timeout' => 5]);
     *     AuthSettings::fake(['timeout' => 5], from: 'production');
     *
     * The base is resolved fresh each call rather than from any instance a
     * previous `fake()` bound, so two calls in one test do not accumulate.
     *
     * @param  array<string, mixed>  $properties
     */
    public static function fake(array $properties = [], ?string $from = null): static
    {
        $instance = ($from === null ? static::resolve() : static::from($from))->with($properties);

        app()->instance(static::class, $instance);

        return $instance;
    }

    /**
     * Return a copy of this instance with the given properties replaced.
     *
     * The copy is cloned rather than rebuilt through the constructor, so it
     * never depends on the constructor's parameters: cloning copies whatever
     * shape the runtime class actually has — a local override included.
     * Properties that are not named keep their current values.
     *
     * An unknown name is rejected rather than ignored: a typo that silently
     * changed nothing would leave the caller asserting against the
     * environment's real value while believing it had been replaced. A wrong
     * type raises a `TypeError` on assignment, so it surfaces here rather than
     * wherever the value is later read.
     *
     * `readonly` properties cannot be replaced this way; classes generated by
     * `env-settings:make` do not declare any.
     *
     * @param  array<string, mixed>  $properties
     */
    public function with(array $properties): static
    {
        $known = $this->publicPropertyNames();
        $unknown = array_values(array_diff(array_keys($properties), $known));

        if ($unknown !== []) {
            throw new InvalidArgumentException(sprintf(
                'Unknown %s on %s: %s. Known properties: %s.',
                count($unknown) === 1 ? 'property' : 'properties',
                static::class,
                implode(', ', $unknown),
                $known === [] ? '(none)' : implode(', ', $known),
            ));
        }

        $copy = clone $this;

        foreach ($properties as $name => $value) {
            $copy->{$name} = $value;
        }

        return $copy;
    }

    /**
     * Return the public, typed properties of this settings instance as an array.
     *
     * Nested {@see EnvironmentSettings} instances are recursively expanded so the
     * result is a plain, JSON-serialisable structure.
     *
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        $reflection = new ReflectionClass($this);
        $data = [];

        foreach ($reflection->getProperties(ReflectionProperty::IS_PUBLIC) as $property) {
            if ($property->isStatic()) {
                continue;
            }

            $data[$property->getName()] = $this->normalise($property->getValue($this));
        }

        return $data;
    }

    /**
     * The names of the public, non-static properties of this instance.
     *
     * @return list<string>
     */
    private function publicPropertyNames(): array
    {
        $names = [];

        foreach ((new ReflectionClass($this))->getProperties(ReflectionProperty::IS_PUBLIC) as $property) {
            if (! $property->isStatic()) {
                $names[] = $property->getName();
            }
        }

        return $names;
    }

    /**
     * Reduce a property value to something JSON can represent.
     *
     * Enums are unwrapped here rather than left to `json_encode`: a backed enum
     * would survive, but a pure one has no default serialisation, so a single
     * such property turns the whole encoded payload into `false` with no
     * exception to point at the cause.
     */
    private function normalise(mixed $value): mixed
    {
        if ($value instanceof self) {
            return $value->toArray();
        }

        if ($value instanceof BackedEnum) {
            return $value->value;
        }

        if ($value instanceof UnitEnum) {
            return $value->name;
        }

        if (is_array($value)) {
            return array_map(fn (mixed $item): mixed => $this->normalise($item), $value);
        }

        return $value;
    }
}
